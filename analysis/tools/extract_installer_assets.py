#!/usr/bin/env python3
"""Extract the GameInstaller UI assets from an Asphalt 5 3.4.1 APK.

The native installer renders the exact same screens as the Java activity:

  gameloft_logo.bsprite  + gameloft_logo_01.rgba
  interface_menu.bsprite + interface_menu_01.rgba
  font_menu.bsprite      + font_menu_01.rgba
  datalink.txt, serialkey.txt, font_map.h

Usage:
    python extract_installer_assets.py --apk "Asphalt 5 3.4.1.apk" ^
        --out port/a5host/assets/installer

The PNG sheets are converted to raw RGBA because the host has no PNG decoder.
`font_map.h` is copied from analysis/autogen/font_map.h when present (the
checked-in interoperability map); otherwise it can be regenerated from a jadx
dump of ASprite_A5.java.
"""
from __future__ import annotations

import argparse
import io
import pathlib
import re
import struct
import zipfile

ROOT = pathlib.Path(__file__).resolve().parents[2]
DEFAULT_APK = ROOT / "Asphalt 5 3.4.1.apk"
DEFAULT_OUT = ROOT / "port" / "a5host" / "assets" / "installer"
FONT_MAP = ROOT / "analysis" / "autogen" / "font_map.h"
JADX_SPRITE = (ROOT / "analysis" / "jadx-out" / "sources" / "com" / "gameloft" /
               "android" / "GAND" / "GloftA5HD" / "ASprite_A5.java")

NAMES = ("gameloft_logo", "interface_menu", "font_menu")


def _write_font_map(out_dir: pathlib.Path) -> None:
    if FONT_MAP.exists():
        (out_dir / "font_map.h").write_bytes(FONT_MAP.read_bytes())
        print("font_map.h: copied from %s" % FONT_MAP)
        return
    if not JADX_SPRITE.exists():
        raise SystemExit(
            "font_map.h missing: put the interoperability map at %s\n"
            "(or provide a jadx dump of ASprite_A5.java)" % FONT_MAP)
    text = JADX_SPRITE.read_text(encoding="utf-8", errors="replace")
    m = re.search(r"_map_char\s*=\s*\{(.*?)\};", text, re.S)
    if not m:
        raise SystemExit("_map_char not found in %s" % JADX_SPRITE)
    vals = [int(x) for x in re.findall(r"-?\d+", m.group(1))]
    with (out_dir / "font_map.h").open("w", encoding="utf-8") as f:
        f.write("// Auto-generated by analysis/tools/extract_installer_assets.py\n")
        f.write("// ASprite_A5._map_char: character code -> font_menu frame index.\n")
        f.write("#ifndef A5_FONT_MAP_H\n#define A5_FONT_MAP_H\n")
        f.write("static const short a5_font_map[%d] = {\n" % len(vals))
        for i in range(0, len(vals), 16):
            f.write("    " + ",".join(str(v) for v in vals[i:i + 16]) + ",\n")
        f.write("};\n#endif\n")
    print("font_map.h: generated from jadx (%d entries)" % len(vals))


def extract(apk_path: pathlib.Path | str, out_dir: pathlib.Path | str) -> pathlib.Path:
    apk_path = pathlib.Path(apk_path)
    out_dir = pathlib.Path(out_dir)
    out_dir.mkdir(parents=True, exist_ok=True)
    if not apk_path.exists():
        raise SystemExit("APK not found: %s" % apk_path)

    try:
        from PIL import Image
    except ImportError:
        raise SystemExit("Pillow is required: python -m pip install Pillow")

    with zipfile.ZipFile(apk_path) as z:
        names = set(z.namelist())
        for name in NAMES:
            bs_name = "res/raw/%s.bsprite" % name
            png_name = "res/raw/%s_01.png" % name
            if bs_name not in names or png_name not in names:
                raise SystemExit("APK missing %s / %s" % (bs_name, png_name))
            bs = z.read(bs_name)
            png = z.read(png_name)
            (out_dir / ("%s.bsprite" % name)).write_bytes(bs)
            im = Image.open(io.BytesIO(png)).convert("RGBA")
            (out_dir / ("%s_01.rgba" % name)).write_bytes(im.tobytes())
            (out_dir / ("%s_01.size" % name)).write_text("%d %d\n" % im.size,
                                                        encoding="ascii")
            print("%-16s bsprite=%5d png=%dx%d rgba=%d" %
                  (name, len(bs), im.size[0], im.size[1], len(im.tobytes())))

        for raw in ("datalink.txt", "serialkey.txt"):
            entry = "res/raw/" + raw
            if entry not in names:
                raise SystemExit("APK missing %s" % entry)
            (out_dir / raw).write_bytes(z.read(entry))
        print("datalink.txt:", z.read("res/raw/datalink.txt")
              .decode("utf-8", "replace")[:120], "...")

    _write_font_map(out_dir)
    print("installer assets written to", out_dir)
    return out_dir


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--apk", default=str(DEFAULT_APK),
                    help="input Asphalt 5 3.4.1 APK")
    ap.add_argument("--out", default=str(DEFAULT_OUT),
                    help="output assets/installer directory")
    args = ap.parse_args()
    extract(args.apk, args.out)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
